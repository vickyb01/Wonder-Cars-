function mergeSeedCarsWithStored(storedCars: Car[]): Car[] {
  const seedMap = new Map(SEED_CARS.map((c) => [c.id, c]));
  return storedCars.map((stored) => {
    const seed = seedMap.get(stored.id);
    if (!seed) {
      return normalizeCarRecord(stored);
    }
    // Upgrade legacy seed entries that lacked rich showroom dossiers while keeping any admin edits (price, status, featured, gallery, etc.)
    const hasRichDossier = Boolean(stored.exteriorReport && stored.exteriorReport.length > 0 && stored.documents && stored.documents.length > 0);
    if (hasRichDossier) {
      return normalizeCarRecord(stored);
    }
    return normalizeCarRecord({
      ...seed,
      ...stored,
      gallery: stored.gallery && stored.gallery.length > 0 ? stored.gallery : seed.gallery,
      images: stored.images && stored.images.length > 0 ? stored.images : seed.images,
    });
  });
}

function ensureInitialized(): DatabaseState {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (!fs.existsSync(DB_PATH)) {
    const initial: DatabaseState = {
      cars: SEED_CARS,
      enquiries: SEED_ENQUIRIES,
      sellRequests: SEED_SELL_REQUESTS,
      locationSettings: { ...DEFAULT_SHOWROOM_LOCATION_SETTINGS },
    };
    fs.writeFileSync(DB_PATH, JSON.stringify(initial, null, 2), 'utf-8');
    return initial;
  }
  try {
    const raw = fs.readFileSync(DB_PATH, 'utf-8');
    const parsed = JSON.parse(raw) as Partial<DatabaseState>;
    const cars = Array.isArray(parsed.cars) ? mergeSeedCarsWithStored(parsed.cars) : SEED_CARS;
    const rawLoc = parsed.locationSettings;
    const isUnconfigured =
      !rawLoc ||
      (!rawLoc.updatedAt && !rawLoc.address && !rawLoc.latitude && !rawLoc.phone && !rawLoc.email);
    const locationSettings = isUnconfigured
      ? { ...DEFAULT_SHOWROOM_LOCATION_SETTINGS }
      : {
          ...DEFAULT_SHOWROOM_LOCATION_SETTINGS,
          ...normalizeLocationSettings(rawLoc),
        };
    return {
      cars,
      enquiries: Array.isArray(parsed.enquiries) ? parsed.enquiries : SEED_ENQUIRIES,
      sellRequests: Array.isArray(parsed.sellRequests) ? parsed.sellRequests : SEED_SELL_REQUESTS,
      locationSettings,
    };
  } catch {
    const fallback: DatabaseState = {
      cars: SEED_CARS,
      enquiries: SEED_ENQUIRIES,
      sellRequests: SEED_SELL_REQUESTS,
      locationSettings: { ...DEFAULT_SHOWROOM_LOCATION_SETTINGS },
    };
    fs.writeFileSync(DB_PATH, JSON.stringify(fallback, null, 2), 'utf-8');
    return fallback;
  }
}

export function readDb(): DatabaseState {
  return ensureInitialized();
}

export function writeDb(state: DatabaseState): void {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  const tmpPath = `${DB_PATH}.tmp`;
  fs.writeFileSync(tmpPath, JSON.stringify(state, null, 2), 'utf-8');
  fs.renameSync(tmpPath, DB_PATH);
}

export function slugifyCar(year: number, brand: string, model: string): string {
  return `${year}-${brand}-${model}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}
