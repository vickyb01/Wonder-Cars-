function buildInspectedList(
  components: readonly string[],
  overrides: Record<string, Partial<InspectionItem>>,
  fallbackStatus: InspectionItem['status'] = 'Good'
): InspectionItem[] {
  return components.map((component) => ({
    component,
    status: overrides[component]?.status || fallbackStatus,
    notes: overrides[component]?.notes || '',
  }));
}

